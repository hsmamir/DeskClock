#!/usr/bin/env python3
"""
make_vlw_pages.py - the smooth (VLW) fonts of the Date and Weather pages of the landscape UI.

The fonts of make_vlw.py only hold the letters of the day / month names, which is not enough for "Sunny",
"Humidity" or "km/h". This script builds three more fonts and leaves display_fonts.cpp alone:

    PageSm12, PageSm18   Carlito Bold, printable ASCII + the degree sign   (labels, values)
    PageTemp36           Manrope SemiBold 36 px, 0-9, minus, degree sign   (the big temperature)

Usage:   python3 tools/make_vlw_pages.py
Output:  src/display_fonts_pages.cpp, include/display_fonts_pages.h, tools/out/PageSm12.vlw ...
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.argv = [sys.argv[0]]            # make_vlw reads argv[1] as the font file at import time
sys.path.insert(0, HERE)
import make_vlw as mv

ROOT, OUT = mv.ROOT, mv.OUT
ASCII = "".join(chr(c) for c in range(0x21, 0x7F))      # no space: TFT_eSPI draws blanks by itself
SETS = [
    # name, size, code points, font file, weight
    ("PageSm12", 12, mv.charset(ASCII + "\u00b0"), mv.FONT, None),
    ("PageSm18", 18, mv.charset(ASCII + "\u00b0"), mv.FONT, None),
    ("PageTemp36", 36, mv.charset("0123456789-\u00b0"), mv.BIG_FONT, mv.BIG_WEIGHT),
]

def main():
    os.makedirs(OUT, exist_ok=True)
    cpp = ["// display_fonts_pages.cpp - GENERATED by tools/make_vlw_pages.py, do not edit by hand.",
           "// Smooth (VLW) fonts of the Date and Weather pages, see display_fonts_pages.h.",
           "#include <Arduino.h>", '#include "display_fonts_pages.h"', ""]
    hdr = ["// display_fonts_pages.h - GENERATED by tools/make_vlw_pages.py, do not edit by hand.",
           "// Smooth (VLW) fonts of the Date and Weather pages: g.loadFont(PageSm12), draw, g.unloadFont().",
           "//   PageSm12, PageSm18: printable ASCII (no blank glyph, TFT_eSPI draws blanks itself) + the degree sign",
           "//   PageTemp36:         0-9, minus and the degree sign, Manrope SemiBold (the big temperature)",
           "// *_CAPH = height of the digits / capital letters in px.",
           "#pragma once", "#include <Arduino.h>", ""]
    for name, size, codes, fontfile, weight in SETS:
        data, glyphs, asc, desc, caph = mv.build_vlw(size, codes, fontfile, 0,
                                                     os.path.splitext(os.path.basename(fontfile))[0], weight)
        hdr.append("extern const uint8_t %s[]; // %d glyphs, %d bytes" % (name, len(glyphs), len(data)))
        hdr.append("constexpr int16_t %s_CAPH = %d;" % (name.upper(), caph))
        open(os.path.join(OUT, name + ".vlw"), "wb").write(data)
        cpp.append("// %s: size %d, %d glyphs, %d bytes" % (name, size, len(glyphs), len(data)))
        cpp.append(mv.c_array(name, data))
        print("%-10s size %2d  %2d glyphs  %5d bytes  caph %d" % (name, size, len(glyphs), len(data), caph))
    open(os.path.join(ROOT, "src", "display_fonts_pages.cpp"), "w").write("\n".join(cpp))
    open(os.path.join(ROOT, "include", "display_fonts_pages.h"), "w").write("\n".join(hdr) + "\n")

if __name__ == "__main__":
    main()
