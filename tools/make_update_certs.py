#!/usr/bin/env python3
"""Regenerate include/update_certs.h: the root CA certificates the clock trusts when it
checks GitHub for a new firmware release and downloads it (src/update_check.cpp).

GitHub (and the host its release downloads come from) may change its certificate
authority one day. If the "Check for updates" button then reports a TLS error, run:

    pip install certifi
    python tools/make_update_certs.py            # uses the Mozilla list shipped with certifi
    python tools/make_update_certs.py --pem my_roots.pem   # or any PEM file with comments like certifi's

then build and flash the clock once over USB (or the old OTA way). Add a name to
WANTED if the new CA is not listed.
"""
import argparse
import pathlib
import re
import sys

# Subject common names of the roots to embed. Superset on purpose: GitHub (Sectigo / USERTrust)
# and its release storage (Microsoft / DigiCert) have used different chains over time.
WANTED = [
    "USERTrust ECC Certification Authority",
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "DigiCert Global Root G2",
    "DigiCert Global Root CA",
    "Microsoft ECC Root Certificate Authority 2017",
    "Microsoft RSA Root Certificate Authority 2017",
]

OUT = pathlib.Path(__file__).resolve().parent.parent / \
    "include" / "update_certs.h"
BLOCK = re.compile(
    r"((?:#[^\n]*\n)+)(-----BEGIN CERTIFICATE-----\n.*?-----END CERTIFICATE-----\n)", re.S
)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--pem", help="PEM bundle with certifi-style comment headers")
    args = ap.parse_args()
    if args.pem:
        path = args.pem
    else:
        try:
            import certifi
        except ImportError:
            sys.exit("pip install certifi   (or pass --pem FILE)")
        path = certifi.where()
    text = pathlib.Path(path).read_text()
    found = {}
    for header, pem in BLOCK.findall(text):
        m = re.search(r"CN=([^\n]*?)(?: O=| OU=|$)",
                      header) or re.search(r"Label: \"(.*?)\"", header)
        if m:
            found[m.group(1).strip()] = pem
    missing = [n for n in WANTED if n not in found]
    if missing:
        sys.exit("not in the PEM file: " + ", ".join(missing))

    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/make_update_certs.py - do not edit by hand.",
        "// Root CA certificates trusted for the firmware update check (update_check.cpp).",
        "// Included: " + "; ".join(WANTED),
        "// Run the script again if GitHub changes its certificate authority.",
        'static const char UPDATE_ROOT_CAS[] = R"PEM(',
    ]
    body = "".join(found[n] for n in WANTED)
    lines.append(body.rstrip("\n"))
    lines.append(')PEM";')
    OUT.write_text("\n".join(lines) + "\n")
    print(
        f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(WANTED)} certificates)")


if __name__ == "__main__":
    main()
